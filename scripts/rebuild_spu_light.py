"""Extract and lift the verified local SpuLight WWS overlay without rebasing code."""
from pathlib import Path
import argparse
import json
import re
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "tools/ps3recomp"
sys.path.insert(0, str(SDK / "tools"))
from build_spu_workloads import fnv1a64, debase_includes
from lift_jobmods import manual_link_targets, switch_table_targets
from wrap_spu_elf import wrap


def prepare_overlay(elf_path, images, *, offset=0x806C80, size=0x5C60,
                    fingerprint=0x998577C64AEA1F15):
    data = elf_path.read_bytes()
    if data[:6] != b"\x7fELF\x02\x02":
        raise ValueError("Expected a decrypted big-endian ELF64 EBOOT")
    raw = data[offset:offset + size]
    if len(raw) != size:
        raise ValueError("SpuLight binary size mismatch")
    if fnv1a64(raw) != fingerprint:
        raise ValueError("SpuLight fingerprint mismatch")
    if len(raw) < 0x30:
        raise ValueError("Truncated WWS header")
    entry_offset, bss_begin, bss_size = struct.unpack_from(">III", raw, 0x10)
    marker = struct.unpack_from(">I", raw, 0x20)[0]
    base = struct.unpack_from(">I", raw, 0x28)[0]
    # +14 is the BSS offset, not the DMA image length. This title's 0x5C60
    # bytes end before BSS offset 0x5C80; startup clears 0x300 bytes there.
    if (marker != 0xC0DEC0DE or bss_begin < size or base != 0x4000
            or entry_offset < 0x30 or entry_offset >= size or entry_offset % 4
            or bss_begin % 16 or base + bss_begin + bss_size > 0x40000):
        raise ValueError("Invalid or unsupported WWS load/entry header")
    profile = {"fingerprint": f"{fingerprint:016X}", "size": size,
               "base": base, "entry": base + entry_offset,
               "bss_begin": base + bss_begin, "bss_size": bss_size}
    images.mkdir(parents=True, exist_ok=True)
    for suffix, contents in ((".bin", raw),
                             (".elf", wrap(raw, base=base, entry=profile["entry"]))):
        path = images / ("spulight" + suffix)
        if not path.exists() or path.read_bytes() != contents:
            path.write_bytes(contents)
    return profile


def lift_overlay(images, lifted, logs, profile, *, trace=False):
    staged = lifted.parent / "spu_light_stage"
    raw = (images / "spulight.bin").read_bytes()
    extra = sorted(set([profile["base"] + 0x30,
                        *manual_link_targets(raw), *switch_table_targets(raw)]))
    logs.mkdir(exist_ok=True)
    with (logs / "spulight-lift.log").open("w", encoding="utf-8") as log:
        command = [sys.executable, str(SDK / "tools/spu_lifter.py"),
            "--auto-functions", str(images / "spulight.elf"), "--base", "0x4000",
            "--symbol-prefix", "spulight_", "--extra-funcs", ",".join(hex(a) for a in extra),
            "--code-end", "0x9780", "-o", str(staged)]
        if trace:
            command.append("--trace")
        subprocess.run(command, cwd=ROOT,
            stdout=log, stderr=subprocess.STDOUT, check=True)
    for filename in ("spu_recomp.c", "spu_recomp.h"):
        debase_includes(str(staged / filename))
    source = (staged / "spu_recomp.c").read_text(encoding="ascii", errors="replace")
    for address in (0x4030, 0x4AC8, 0x5748, profile["entry"]):
        if not re.search(rf"void spulight_spu_func_{address:08X}\(spu_context\* ctx\)\s*\{{", source):
            raise ValueError(f"SpuLight lift missing verified function {address:08X}")
    registry = lifted / "jobmods_register.c"
    if registry.exists():
        previous = registry.read_text(encoding="ascii", errors="replace")
        if any(name != "spulight_spu_recomp_register" for name in
               re.findall(r"extern void (\w+spu_recomp_register)\(", previous)):
            raise ValueError("Review existing overlay registry before replacing it")
    registration = '''/* Local BCUS98125 SpuLight overlay; generated by rebuild_spu_light.py. */
#include <stdint.h>
extern void spu_begin_image(int);
extern void spu_overlay_register_region(uint32_t, uint32_t, int);
extern void spulight_spu_recomp_register(void);
__attribute__((constructor)) static void infamous2_spulight_register(void) {
    spu_begin_image(200);
    spulight_spu_recomp_register();
    spu_overlay_register_region(0x00816C80u, 0x5C60u, 200);
    spu_begin_image(0);
}
'''
    active = lifted / "spulight"
    active.mkdir(parents=True, exist_ok=True)
    outputs = [(active / name, (staged / name).read_bytes())
               for name in ("spu_recomp.h", "spu_recomp.c")]
    outputs.append((registry, registration.encode("ascii")))
    # Each replacement is atomic. No active output is touched until both
    # generated files and the registry have passed validation.
    for destination, contents in outputs:
        if destination.exists() and destination.read_bytes() == contents:
            continue
        pending = destination.with_suffix(destination.suffix + ".next")
        pending.write_bytes(contents)
        pending.replace(destination)
    (lifted / "spulight/lift-profile.json").write_text(
        json.dumps(dict(profile, trace=trace), indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-build", action="store_true")
    parser.add_argument("--trace", action="store_true",
                        help="generate bounded runtime instruction tracing for SpuLight")
    args = parser.parse_args()
    revision = subprocess.check_output(["git", "-C", str(SDK), "rev-parse", "HEAD"], text=True).strip()
    if revision != "5244db92669b54831c6d3ebb7a96d58c4dbfa6df":
        raise SystemExit("Review toolkit revision before rebuilding SpuLight")
    images = ROOT / "build/game/spu_jobmods"
    lifted = ROOT / "build/game/spu_lifted"
    profile = prepare_overlay(ROOT / "build/game/EBOOT.ELF", images)
    logs = ROOT / "logs"
    logs.mkdir(exist_ok=True)
    lift_overlay(images, lifted, logs, profile, trace=args.trace)
    print(f"SpuLight prepared: {profile}. Log: {logs / 'spulight-lift.log'}")
    if not args.no_build:
        with (logs / "spulight-build.log").open("wb") as log:
            subprocess.run(["cmake", "--build", str(ROOT / "build/infamous2-clang2"),
                "--target", "Infamous2Native", "-j4"], cwd=ROOT,
                stdout=log, stderr=subprocess.STDOUT, check=True)
        print("Native build exit: 0")


if __name__ == "__main__":
    main()
